#!/usr/bin/env bash
# Regenerates plugin/code.js from the individual build scripts.
# The MCP route is capped at 20 tool calls/month on a Figma Starter plan; running the exact same
# Plugin API code as a local development plugin has no such limit.
set -euo pipefail
cd "$(dirname "$0")"
OUT=plugin/code.js
{
  echo '// GENERATED by build-plugin.sh - do not edit directly.'
  echo '// Edit _helpers.js / screens-*.js / fixes-overflow.js and re-run the build script.'
  echo '(async () => {'
  echo '  const page = figma.root.children.find(p => p.name === "Page 1 - Hi Fi") || figma.root.children[0];'
  echo '  await figma.setCurrentPageAsync(page);'
  cat _helpers.js
  echo '  const results = {};'
  for f in screens-13-18 screens-19-22 fixes-overflow; do
    echo "  results['$f'] = await (async () => {"
    cat "$f.js"
    echo '  })();'
  done
  echo '  console.log(JSON.stringify(results, null, 2));'
  echo '  figma.closePlugin("ChronoMap: screens 13-22 built and overflow fixed. See the console for details.");'
  echo '})().catch(e => figma.closePlugin("ChronoMap build failed: " + e.message));'
} > "$OUT"
node --check "$OUT"
echo "built $OUT ($(wc -l < "$OUT") lines) - syntax OK"
